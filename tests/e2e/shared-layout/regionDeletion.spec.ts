import { expect, test } from '@playwright/test';
import { loadSharedLayoutConfig } from './sharedLayoutConfig';

/** One server-backed Keep/Keep journey covers dialog keyboard behavior and subsequent kept-Area usability. */
test('four-way Region preservation keeps Areas usable in Unassigned Places', async ({ page }, testInfo) => {
  const config = loadSharedLayoutConfig();
  const tripId = process.env.WAYFARER_E2E_TRIP_ID!;
  const endpoint = `/api/trips/${tripId}/editor`;
  await page.goto('/Identity/Account/Login');
  await page.getByLabel('Username').fill(config.username);
  await page.getByLabel('Password').fill(config.password);
  await Promise.all([page.waitForURL(url => !url.pathname.endsWith('/Account/Login')), page.getByRole('button', { name: 'Log in' }).click()]);
  await page.goto(`/User/Trip/Edit/${tripId}`);
  await expect(page.locator('.trip-editor-workspace')).toBeVisible();
  const token = await page.locator('#trip-editor-antiforgery input').inputValue();
  const post = async (path: string, data: unknown) => {
    const response = await page.request.post(endpoint + path, { headers: { RequestVerificationToken: token }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return (await response.json()).data;
  };
  const source = await post('/regions', { name: 'Preserve this Region', notesHtml: '<p>Region metadata</p>', coverImage: null, center: null });
  const polygon = { type: 'Polygon', coordinates: [[[23,37],[24,37],[24,38],[23,38],[23,37]], [[23.2,37.2],[23.2,37.4],[23.4,37.4],[23.4,37.2],[23.2,37.2]]] };
  const area = await post(`/regions/${source.id}/areas`, { name: 'Kept polygon with hole', notesHtml: '<p>Area notes</p>', fillHex: '#123456', geometry: polygon });
  const second = await post(`/regions/${source.id}/areas`, { name: 'Second kept Area', notesHtml: null, fillHex: '#abcdef', geometry: polygon });
  await page.reload();
  const card = page.locator(`[data-region-id="${source.id}"]`);
  await card.locator('.trip-editor-region-card__header').getByRole('button', { name: 'Edit', exact: true }).click();
  await card.getByLabel('Name', { exact: true }).fill('Unsaved Region draft');
  await card.getByRole('button', { name: 'Delete', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Delete Region ‘Preserve this Region’?' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await expect(dialog.getByRole('radio', { name: /Keep \(recommended\)/ })).toHaveCount(2);
  for (const radio of await dialog.getByRole('radio', { name: /Keep \(recommended\)/ }).all()) await expect(radio).toBeChecked();
  await dialog.press('Escape'); await expect(dialog).toHaveCount(0);
  await expect(card).toBeVisible();
  await expect(card.getByLabel('Name', { exact: true })).toHaveValue('Unsaved Region draft');
  await card.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Delete Region · keep Places and Areas', exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath('region-deletion-keep-keep.png') });
  await dialog.getByRole('button', { name: 'Delete Region · keep Places and Areas', exact: true }).click();
  await expect(dialog).toHaveCount(0); await expect(card).toHaveCount(0);
  await page.reload();
  const current = await (await page.request.get(endpoint)).json();
  const canonical = Object.values(current.regionsById).find((r: any) => r.name === 'Unassigned Places') as any;
  expect(current.areasById[area.id].regionId).toBe(canonical.id);
  expect(current.areasById[area.id].geometry.coordinates).toEqual(polygon.coordinates);
  const unassigned = page.locator(`[data-region-id="${canonical.id}"]`);
  await expect(unassigned).toBeVisible();
  await expect(unassigned.locator('.trip-editor-region-card__header').getByRole('button', { name: 'Edit', exact: true })).toHaveCount(0);
  await expect(unassigned.getByRole('button', { name: 'Add Area', exact: true })).toHaveCount(0);
  await page.getByPlaceholder('Search regions, places, areas, segments').first().fill('Kept polygon');
  await expect(unassigned).toContainText('Kept polygon with hole');
  await page.getByPlaceholder('Search regions, places, areas, segments').first().fill('');
  const row = page.locator(`[data-area-id="${area.id}"]`);
  await row.getByRole('button', { name: 'Drag to reorder area' }).focus();
  await page.keyboard.press('ArrowDown');
  await expect.poll(async () => (await (await page.request.get(endpoint)).json()).areaOrderByRegionId[canonical.id]).toEqual([second.id, area.id]);
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  const name = page.getByLabel('Name', { exact: true });
  await name.fill('Edited kept polygon');
  await page.getByRole('button', { name: 'Save Area', exact: true }).click();
  await expect.poll(async () => (await (await page.request.get(endpoint)).json()).areasById[area.id].name).toBe('Edited kept polygon');
  const saved = (await (await page.request.get(endpoint)).json()).areasById[area.id];
  expect(saved.geometry.coordinates).toEqual(polygon.coordinates); expect(saved.fillHex).toBe('#123456');
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(row).toHaveCount(0);
});
